"""Generate docs/APEX_CONCEPT_COVERAGE.md: how fully each catalogued concept is read.

Levels (strongest first):
  FULL       a registered concept module reads it in full (applicability, implications,
             invalidation, objective/milestones, requirements, management meaning)
  DATA-GATED a registered reader exists, but a named external feed is required for
             a complete interpretation; missing data remains explicitly unknown
  MEASURED   at least one of its declared measurements is produced by live code, but
             no module reads the concept in full (facts only; name match, not quality)
  UNMEASURED nothing in live code produces any of its declared measurements

Run ``python scripts/concept_coverage.py`` to rewrite the register, or with
``--check`` to fail when it is out of date.
"""

from __future__ import annotations

import re
import difflib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DOC = ROOT / "docs" / "APEX_CONCEPT_COVERAGE.md"
_CATALOGS = {"cognition/analytical_knowledge.py", "cognition/strategy_knowledge.py"}


def _producer_source() -> str:
    files = subprocess.check_output(["git", "ls-files", "*.py"], cwd=ROOT, text=True).split()
    chunks = []
    for rel in files:
        if rel.startswith(("tests/", "dashboard/tests/", "scripts/", "node_modules")) or rel in _CATALOGS:
            continue
        if rel.startswith("cognition/concepts/"):
            continue
        chunks.append((ROOT / rel).read_text(encoding="utf-8", errors="ignore").lower())
    return "\n".join(chunks)


def build() -> str:
    from cognition.analytical_knowledge import _ROWS
    from cognition.concepts import CONCEPT_MODULES
    from cognition.strategy_knowledge import STRATEGY_LENSES

    full_methods = {k for m in CONCEPT_MODULES for k in m.covers_methods}
    full_lenses = {k for m in CONCEPT_MODULES for k in m.covers_lenses}
    gated_methods = {key: reason for module in CONCEPT_MODULES
                     for key, reason in (getattr(module, "data_gated_methods", {}) or {}).items()}
    gated_lenses = {key: reason for module in CONCEPT_MODULES
                    for key, reason in (getattr(module, "data_gated_lenses", {}) or {}).items()}
    blob = _producer_source()

    def measured(tokens: list[str]) -> bool:
        return any(re.search(r"(?<![a-z0-9])" + re.escape(t.lower()) + r"(?![a-z0-9])", blob) for t in tokens)

    lines = [
        "# Apex concept coverage register",
        "",
        "_Generated by `scripts/concept_coverage.py` (do not edit by hand)._",
        "",
        "FULL = read in full; DATA-GATED = reader exists but a named feed is missing; "
        "MEASURED = some declared measurement exists; UNMEASURED = no declared measurement exists.",
        "",
    ]
    counts = {"FULL": 0, "DATA-GATED": 0, "MEASURED": 0, "UNMEASURED": 0}
    rows = []
    for row in _ROWS:
        key, family, name, _domains, meas = row[0], row[1], row[2], row[3], row[4]
        if key in full_methods:
            level, display = "FULL", "FULL"
        elif key in gated_methods:
            level, display = "DATA-GATED", f"DATA-GATED — {gated_methods[key]}"
        elif measured(meas.split()):
            level, display = "MEASURED", "MEASURED"
        else:
            level, display = "UNMEASURED", "UNMEASURED"
        counts[level] += 1
        rows.append((family, name, key, display))
    lines += [f"## Analytical methods ({len(_ROWS)})",
              f"FULL {counts['FULL']} · DATA-GATED {counts['DATA-GATED']} · MEASURED {counts['MEASURED']} · UNMEASURED {counts['UNMEASURED']}", "",
              "| Family | Method | Key | Level |", "|---|---|---|---|"]
    for family, name, key, level in sorted(rows):
        lines.append(f"| {family} | {name} | `{key}` | {level} |")
    lens_counts = {"FULL": 0, "DATA-GATED": 0, "MEASURED": 0, "UNMEASURED": 0}
    lens_rows = []
    for lens in STRATEGY_LENSES:
        if lens.key in full_lenses:
            level, display = "FULL", "FULL"
        elif lens.key in gated_lenses:
            level, display = "DATA-GATED", f"DATA-GATED — {gated_lenses[lens.key]}"
        elif measured(list(lens.anchors)):
            level, display = "MEASURED", "MEASURED"
        else:
            level, display = "UNMEASURED", "UNMEASURED"
        lens_counts[level] += 1
        lens_rows.append((lens.name, lens.key, display))
    lines += ["", f"## Strategy lenses ({len(STRATEGY_LENSES)})",
              f"FULL {lens_counts['FULL']} · DATA-GATED {lens_counts['DATA-GATED']} · MEASURED {lens_counts['MEASURED']} · UNMEASURED {lens_counts['UNMEASURED']}", "",
              "| Lens | Key | Level |", "|---|---|---|"]
    for name, key, level in sorted(lens_rows):
        lines.append(f"| {name} | `{key}` | {level} |")
    lines += ["", "## Registered concept modules", ""]
    for m in CONCEPT_MODULES:
        line = (f"- `{m.key}` ({m.family}) — methods: {', '.join(m.covers_methods) or '-'}; "
                f"lenses: {', '.join(m.covers_lenses) or '-'}")
        gated = getattr(m, "data_gated_methods", {}) or {}
        if gated:
            line += "; data-gated: " + ", ".join(f"{key} ({reason})" for key, reason in gated.items())
        lines.append(line)
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current != text:
            print("docs/APEX_CONCEPT_COVERAGE.md is out of date; run scripts/concept_coverage.py")
            print("".join(difflib.unified_diff(
                current.splitlines(keepends=True),
                text.splitlines(keepends=True),
                fromfile="docs/APEX_CONCEPT_COVERAGE.md",
                tofile="generated/APEX_CONCEPT_COVERAGE.md",
            )))
            return 1
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
